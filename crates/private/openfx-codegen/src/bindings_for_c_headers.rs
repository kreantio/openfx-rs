fn extract_number(input: &str) -> Option<u32> {
    let mut i_start = -1;
    let mut i_end = -1;

    for (i, ch) in input.chars().enumerate() {
        if ch.is_ascii_digit() {
            if i_start == -1 {
                i_start = i as i32;
            }
            i_end = i as i32;
        } else if i_start != -1 {
            break;
        }
    }

    if i_start == -1 || i_end == -1 {
        None
    } else {
        let number_str = &input[i_start as usize..=i_end as usize];
        Some(number_str.parse::<u32>().unwrap())
    }
}
